export const CATEGORIES = TAXONOMY.map((c) => c.name);
export const subcategoriesOf = (cat) => TAXONOMY.find((c) => c.name === cat)?.subs.map((s) => s.name) || [];
export const OTHER = { category: 'Друго', subcategory: 'Друго' };

/** Force an (AI-supplied or imported) pair into a valid category/subcategory. */
export function validateCategory(category, subcategory) {
  const c = TAXONOMY.find((x) => x.name === category);
  if (!c) return null;
  const sub = c.subs.find((s) => s.name === subcategory);
  return { category: c.name, subcategory: sub ? sub.name : c.subs[0].name === 'Друго' ? 'Друго' : '' };
}

/** Compact text for prompts: "Категория: подкатегория1, подкатегория2" per line. */
export const taxonomyForPrompt = () => TAXONOMY.map((c) => `- ${c.name}: ${c.subs.map((s) => s.name).join(' | ')}`).join('\n');

/**
 * Offline keyword classifier: returns { category, subcategory } best matching the text, or OTHER.
 * Used when no AI is available and to repair missing subcategories.
 */
export function guessCategory(text) {
  const t = String(text || '').toLowerCase();
  let best = null, bestScore = 0;
  for (const c of TAXONOMY) for (const s of c.subs) {
    let score = 0;
    for (const k of s.kw) if (t.includes(k)) score += k.length;
    if (score > bestScore) { bestScore = score; best = { category: c.name, subcategory: s.name }; }
  }
  return best || OTHER;
}
